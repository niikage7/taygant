/** Пользователь платформы. */
export interface User {
  /** Уникальный идентификатор пользователя. */
  id: string;
  /** Полное имя пользователя. */
  fullName: string;
  /** Email пользователя, используется как логин. */
  email: string;
  /** Организационное подразделение пользователя. */
  department?: string;
  /** Должность/специализация пользователя. */
  position?: string;
  /** Ссылка на изображение аватара пользователя. */
  avatarUrl: string | null;
}
