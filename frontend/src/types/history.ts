import type { User } from "./user";

/** Запись в журнале изменений (аудите) задачи. */
export interface HistoryEntry {
  /** Идентификатор записи истории. */
  id: string;
  /** Идентификатор задачи, к которой относится запись. */
  taskId: string;
  /** Пользователь, совершивший действие. */
  actor: User;
  /** Код совершённого действия. */
  action: string;
  /** Изменённое поле задачи (если действие затронуло конкретное поле). */
  field: string | null;
  /** Значение поля до изменения. */
  oldValue: string | null;
  /** Значение поля после изменения. */
  newValue: string | null;
  /** Дата и время изменения. */
  createdAt: string;
}
