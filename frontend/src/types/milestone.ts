import type { MilestoneStatus } from "./common";

/** Контрольная точка (веха) проекта — значимое событие с плановой датой. */
export interface Milestone {
  /** Идентификатор контрольной точки. */
  id: string;
  /** Идентификатор проекта, которому принадлежит веха. */
  projectId: string;
  /** Короткий код контрольной точки. */
  code?: string;
  /** Название контрольной точки. */
  name: string;
  /** Плановая дата достижения контрольной точки. */
  plannedDate: string;
  /** Фактическая дата достижения контрольной точки (заполняется по факту). */
  actualDate: string | null;
  /** Текущий статус контрольной точки. */
  status: MilestoneStatus;
  /** Прогнозируемое отставание от плановой даты, дней. */
  riskDays: number | null;
}

/** Данные для создания или изменения контрольной точки. */
export interface MilestoneCreateRequest {
  /** Короткий код контрольной точки. */
  code?: string;
  /** Название контрольной точки. */
  name: string;
  /** Плановая дата достижения контрольной точки. */
  plannedDate: string;
}
